#!/usr/bin/env bash
# Wires an unpacked extension into a Chromium-family launcher so every launch
# loads it. Shared by install_leechblock.sh and install_ublock.sh, which used to
# carry two copies of this logic; sourced, so it inherits the caller's strict
# mode and info/warn helpers.
#
# Chromium keeps only the LAST --load-extension switch, so every path below
# extends the one existing list instead of adding a second flag.
#
# Order of preference, safest first:
#   1. the launcher reads ~/.config/<name>-flags.conf: write the flag there and
#      touch no system file at all;
#   2. the launcher is a script with a top-level `exec ... "$@"` line: extend
#      or insert the flag on that line;
#   3. the launcher is a compiled binary: replace it with a wrapper script.
# A script that fits none of these is left alone with a warning. Wrapping a
# script is what broke every browser on 2026-11-21: browser-preexec-wrapper is
# one script behind many symlinked names and picks the browser by basename
# "$0", so exec'ing it as "<name>.orig" made it run the flag as the browser.

# The flags file a launcher reads, or a non-zero return when it reads none.
# Only launchers checked on this machine are listed: Arch's chromium launcher
# (strings /usr/bin/chromium) and Helium's helium-wrapper both read these.
browser_flags_conf() {
	local dir="${XDG_CONFIG_HOME:-$HOME/.config}"
	case "$1" in
	chromium) printf '%s/chromium-flags.conf\n' "$dir" ;;
	helium-browser) printf '%s/helium-browser-flags.conf\n' "$dir" ;;
	*) return 1 ;;
	esac
}

# Collapse every --load-extension line of conf $1 into one line that also
# lists $2, keeping path order and every other line where it was. Written in
# place, not mv'd, so a symlinked config stays linked.
merge_extension_into_conf() {
	local conf="$1" ext="$2" line path joined="" out="" placed=0
	local -a parts
	local -A seen=()
	mkdir -p "$(dirname "$conf")"
	[[ -f $conf ]] || : >"$conf"
	while IFS= read -r line || [[ -n $line ]]; do
		[[ $line =~ ^--load-extension=\"?([^\"]*)\"?$ ]] || continue
		IFS=',' read -r -a parts <<<"${BASH_REMATCH[1]}"
		for path in "${parts[@]}"; do
			[[ -z $path || -n ${seen[$path]:-} ]] && continue
			seen[$path]=1
			joined+="${joined:+,}$path"
		done
	done <"$conf"
	[[ -n ${seen[$ext]:-} ]] || joined+="${joined:+,}$ext"
	while IFS= read -r line || [[ -n $line ]]; do
		if [[ $line == --load-extension=* ]]; then
			((placed)) || out+="--load-extension=$joined"$'\n'
			placed=1
		else
			out+="$line"$'\n'
		fi
	done <"$conf"
	((placed)) || out+="--load-extension=$joined"$'\n'
	[[ $out == "$(cat "$conf")"$'\n' ]] && return 0
	printf '%s' "$out" >"$conf"
}

# Case 2: add $2 to the quoted --load-extension list on the exec line of script
# $1, or insert one before "$@". Returns non-zero when there is no such line.
patch_exec_line() {
	local script="$1" ext="$2"
	grep -qE '^exec .* "\$@"' "$script" || return 1
	[[ -f "$script.orig" ]] || sudo cp -a "$script" "$script.orig"
	if grep -qE -- '^exec .*--load-extension="[^"]*"' "$script"; then
		sudo sed -i -E "/^exec /s|--load-extension=\"([^\"]*)\"|--load-extension=\"\1,${ext}\"|" "$script"
	else
		sudo sed -i "s|^exec \(.*\) \"\\\$@\"|exec \1 --load-extension=\"$ext\" \"\\\$@\"|" "$script"
	fi
}

# Case 3: replace binary $1 with a script that execs a copy of it plus the
# flag. The copy is refreshed on every run: a .orig left from an older install
# would otherwise launch a stale browser after every package upgrade.
wrap_binary() {
	local bin="$1" ext="$2" tag="$3"
	local orig="$bin.orig"
	sudo cp -a "$bin" "$orig"
	sudo tee "$bin" >/dev/null <<WRAP
#!/usr/bin/env bash
# __${tag}_WRAPPER__ — auto-generated by browser_extension_wiring.sh
# Original backed up at: $orig
exec "$orig" --load-extension="$ext" "\$@"
WRAP
	sudo chmod +x "$bin"
}

# Wire extension $3 into browser command $1 (display name $2); $4 tags the
# wrapper written in case 3. Returns 0 when the browser loads it afterwards.
wire_extension_into_browser() {
	local bin="$1" pretty="$2" ext="$3" tag="$4"
	local bin_path real_bin conf
	bin_path=$(command -v "$bin" || true)
	[[ -n $bin_path ]] || return 1

	if conf=$(browser_flags_conf "$bin"); then
		merge_extension_into_conf "$conf" "$ext"
		info "✓ $pretty loads $ext via $conf"
		return 0
	fi

	real_bin=$(readlink -f "$bin_path")
	if grep -qE -- "--load-extension=\"([^\"]*,)?${ext//\//\\/}(,[^\"]*)?\"" "$real_bin" 2>/dev/null; then
		info "$pretty ($bin) already loads $ext — skipping"
		return 0
	fi

	pkill -f "$real_bin" 2>/dev/null || true
	sleep 1
	if file "$real_bin" 2>/dev/null | grep -qi 'text\|script'; then
		if patch_exec_line "$real_bin" "$ext"; then
			info "✓ $pretty exec line in $real_bin now loads $ext"
			return 0
		fi
		warn "$pretty: $real_bin is a script without a top-level exec \"\$@\" line; not touching it"
		return 1
	fi

	wrap_binary "$real_bin" "$ext" "$tag"
	info "✓ $pretty now always launches with $ext"
}
